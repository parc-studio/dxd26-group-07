function glyph(c){if(c===' ')return null;return F[c]||F[c.toUpperCase()]||F['?']}
// draw text as dots; cols = chars visible
function dots(ctx,W,H,text,{color='#ff4f00',dim='rgba(255,79,0,.08)',chars=10,pad=4,align='left'}={}){
  ctx.clearRect(0,0,W,H);
  const cols=chars*6-1, pitch=Math.min((W-pad*2)/cols,(H-pad*2)/7), r=pitch*.36;
  const ox=pad+(W-pad*2-cols*pitch)/2, oy=(H-7*pitch)/2;
  const s=(text||'').slice(0,chars); const start=align==='right'?chars-s.length:0;
  for(let ci=0;ci<chars;ci++){const g=glyph(s[ci-start]||' ');
    for(let y=0;y<7;y++)for(let x=0;x<5;x++){const on=g&&g[y][x]==='#';ctx.fillStyle=on?color:dim;ctx.beginPath();ctx.arc(ox+(ci*6+x)*pitch+pitch/2,oy+y*pitch+pitch/2,r,0,7);ctx.fill()}}
}
